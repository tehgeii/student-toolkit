/** Colors for deadline states that read well in both themes. */
object StatusColors {
    val danger = Color(0xFFDC2626)
    val warning = Color(0xFFD97706)
    val ok = Color(0xFF16A34A)
    val neutral = Color(0xFF64748B)
}

@Composable
fun StudentToolkitTheme(theme: ThemeMode, dynamicColor: Boolean, content: @Composable () -> Unit) {
    val dark = when (theme) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }
    val context = LocalContext.current
    val colors = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (dark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        dark -> DarkColors
        else -> LightColors
    }
    val activity = context as? ComponentActivity
    DisposableEffect(activity, dark) {
        // Keep status/navigation bar icons readable when the app theme differs from the system theme.
        activity?.enableEdgeToEdge(
            statusBarStyle = SystemBarStyle.auto(android.graphics.Color.TRANSPARENT, android.graphics.Color.TRANSPARENT) { dark },
            navigationBarStyle = SystemBarStyle.auto(android.graphics.Color.TRANSPARENT, android.graphics.Color.TRANSPARENT) { dark },
        )
        onDispose {}
    }
    MaterialTheme(colorScheme = colors, content = content)
}
